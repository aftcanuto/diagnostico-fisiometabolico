assert.equal(validateEnteredJump(newJumpTrial('sj', 'empty')).status, 'pendente');
assert.equal(validateEnteredJump({ ...newJumpTrial('sj', 'normal'), altura_cm: 30 }).status, 'valida');
assert.equal(validateEnteredJump({ ...newJumpTrial('cmj', 'flight'), voo_ms: 500 }).status, 'valida');
assert.equal(validateEnteredJump({ ...newJumpTrial('sj', 'high'), altura_cm: 300 }).status, 'pendente');
assert.equal(validateEnteredJump({ ...newJumpTrial('dj', 'contact'), altura_cm: 30 }).status, 'pendente');
assert.equal(validateEnteredJump({ ...newJumpTrial('dj', 'complete'), altura_cm: 30, contato_ms: 200 }).status, 'valida');
assert.equal(validateEnteredJump({ ...newJumpTrial('sj', 'excluded'), altura_cm: 30, status: 'excluida', justificativa: 'Tecnica inadequada' }).status, 'excluida');
assert.equal(validateEnteredJump({ ...newJumpTrial('sj', 'inconsistent'), altura_cm: 30, voo_ms: 100 }).status, 'pendente');
assert.equal(newJumpTrial('vj', 'vj-technique').tecnica_bracos, 'cintura');
assert.equal(newJumpTrial('cmj', 'cmj-technique').tecnica_bracos, 'livres');

const d = newJumpData();
d.apto = d.familiarizacao = true; d.peso_kg = 75;
d.protocolos = ['sj', 'vj', 'cmj', 'dj', 'unilateral_d', 'unilateral_e', 'repetidos'];
d.repetidos_serie_completa = true;
for (const p of d.protocolos) for (let i = 0; i < (p === 'repetidos' ? 12 : 3); i++) {
  const h = p === 'sj' ? 25 : p === 'cmj' ? 35 : p === 'unilateral_d' ? 20 : p === 'unilateral_e' ? 18 : 30;
  d.tentativas.push({ ...newJumpTrial(p, `${p}-${i}`), altura_cm: h, contato_ms: p === 'dj' || p === 'repetidos' ? 200 : null, potencia_w: 3000, status: 'valida' });
}
assert.equal(jumpSchema.safeParse(d).success, true);
const summary = jumpSummary(d);
assert.equal(formatCalendarDate('2026-06-15'), '15/06/2026');
assert.equal(formatCalendarDate('invalid'), 'invalid');
const simulatedContext = jumpClinicalContext({ ...d, observacoes: 'DADOS SIMULADOS para teste de software' });
assert.equal('resultados' in simulatedContext, false);
assert.equal('simulado' in simulatedContext && simulatedContext.simulado, true);
assert.equal('resultados' in jumpClinicalContext(d), true);
assert.equal(summary.pronto, true);
assert.equal(summary.eur_altura, 1.2);
assert.equal(summary.eur_protocolo, 'vj');
const legacy = { ...d, protocolos: d.protocolos.filter(p => p !== 'vj'), tentativas: d.tentativas.filter(t => t.protocolo !== 'vj').map(({ tecnica_bracos: _, ...t }) => t) };
assert.equal(jumpSchema.safeParse(legacy).success, true, 'Coleta anterior sem VJ nem tecnica por tentativa deve continuar valida');
assert.equal(jumpSummary(legacy).eur_protocolo, 'cmj');
assert.equal(jumpSummary(legacy).eur_altura, 1.4);
assert.equal(summary.assimetria_altura_percent, 10);
assert.equal(summary.grupos.find(x => x.protocolo === 'dj')?.rsi_medio, 1.4999999999999998);
assert.equal(trialMetrics(d.tentativas[0], 75).potencia_w_kg, 40);
assert.equal(trialMetrics(d.tentativas[0], null).potencia_w_kg, null);
assert.equal(trialMetrics(d.tentativas[0], 75).altura_mm, 250);
const fromFlight = { ...newJumpTrial('cmj', 'f'), voo_ms: 500 };
assert.ok(Math.abs(trialMetrics(fromFlight, null).altura_cm! - 30.64578125) < 0.00001);
assert.equal(trialMetrics(newJumpTrial('cmj', 'empty'), null).altura_cm, null);
assert.equal(trialMetrics({ ...d.tentativas[0], contato_ms: 200 }, 75).rsi, null, 'SJ must not receive DJ RSI');
const suspicious = { ...newJumpTrial('cmj', 'suspect'), altura_cm: 242, voo_ms: 1405, status: 'valida' as const };
assert.ok(trialWarnings(suspicious).length);
const bad = { ...d, tentativas: d.tentativas.map(t => t.id === 'cmj-0' ? suspicious : t) };
assert.equal(jumpSummary(bad).pronto, false);
assert.equal(jumpSummary(bad).grupos.find(g => g.protocolo === 'cmj')?.n, 2);
assert.equal(jumpSchema.safeParse({ ...d, tentativas: [{ ...suspicious, status: 'excluida' }] }).success, false);
assert.equal(jumpSchema.safeParse({ ...d, peso_kg: -1 }).success, false);
assert.equal(jumpSchema.safeParse({ ...d, duracao_s: 30 }).success, false);
assert.equal(jumpSchema.safeParse({ ...d, tentativas: [...d.tentativas, d.tentativas[0]] }).success, false);
assert.equal(jumpSummary({ ...d, repetidos_serie_completa: false }).pronto, false);
assert.equal(jumpSummary({ ...d, familiarizacao: false }).pronto, false);
assert.equal(jumpSummary({ ...d, tentativas: [...d.tentativas, { ...d.tentativas[0], id: 'fourth' }] }).pronto, false);
assert.equal(jumpSummary({ ...d, tentativas: d.tentativas.map(t => t.protocolo === 'dj' ? { ...t, contato_ms: null, justificativa: 'reviewed' } : t) }).pronto, false);
assert.equal(jumpComparable(d, { ...d, altura_queda_cm: 20 }, 'dj'), false);
assert.equal(jumpComparable(d, { ...d, altura_queda_cm: 20 }, 'cmj'), true);
assert.equal(jumpComparable(d, { ...d, bracos: 'livres' }, 'cmj'), true, 'Tecnica explicita do CMJ nao depende do campo legado global');
assert.equal(jumpComparable(d, { ...d, tentativas: d.tentativas.map(t => t.protocolo === 'cmj' ? { ...t, tecnica_bracos: 'cintura' as const } : t) }, 'cmj'), false);
assert.match(jumpProtocolTechnique(d, 'vj'), /maos na cintura/);
assert.match(jumpProtocolTechnique(d, 'cmj'), /bracos livres/);
assert.equal(jumpAnalysisUsable({ tipo: 'jump_test', conteudo: { _jump_updated_at: 'old' } }, { updated_at: 'new' }), false);
assert.equal(jumpAnalysisUsable({ tipo: 'jump_test', conteudo: { _jump_updated_at: 'same' } }, { updated_at: 'same' }), true);
assert.equal(jumpAnalysisUsable({ tipo: 'anamnese' }, { updated_at: 'new' }), true);
const prompt = promptJumpTest({ nome: 'Pessoa ficticia', sexo: 'F', idade: 35 }, { ...d, contexto_integrado: { data_atual: '2026-09-23', historico: [] } });
assert.match(prompt.system, /medicamentos passados nao sao uso atual/);
assert.match(prompt.system, /simulados, ficticios ou de teste/);
assert.match(prompt.user, /contextual/);
assert.match(prompt.user, /2026-09-23/);
assert.match(jumpEvolutionHtml(d, { ...d, tentativas: d.tentativas.map(t => t.protocolo === 'cmj' ? { ...t, tecnica_bracos: 'cintura' as const } : t) }), /Nao comparavel/);
assert.doesNotMatch(jumpReportHtml({ ...d, observacoes: '<script>alert(1)</script>' }), /<script>alert/);
assert.doesNotMatch(jumpReportHtml(bad, 'SHOULD_NOT_SHOW'), /SHOULD_NOT_SHOW/);

