import assert from 'node:assert/strict';
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { newJumpData, newJumpTrial, jumpSchema, jumpSummary, trialMetrics, trialWarnings, jumpComparable, jumpAnalysisUsable, jumpProtocolTechnique } from '../src/lib/jump-test';
import { jumpReportHtml, jumpEvolutionHtml } from '../src/lib/pdf/jump-test';
import { renderLaudoHTML } from '../src/lib/pdf/template';
import { promptJumpTest } from '../src/lib/ai/prompts';
